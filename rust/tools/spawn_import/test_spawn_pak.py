"""Unit tests of the 10.x spawner reader and the zone transform.

    python -I -m unittest discover -s rust/tools/spawn_import -p "test_*.py"

The cross-check against the 199 event entries already shipped in the world files is optional
(it needs the audit's extracted 10.x/1.2 trees):

    AAEMU_SPAWN_AUDIT=D:/aaemu-audits/research/spawns \
        python -I -m unittest rust.tools...  # see discover above
"""
import glob
import json
import math
import os
import tempfile
import unittest

from fill_spawns import world_entries
from spawn_pak import parse_spawners, transform, zone_origins

G = """spawner
    spawnerId 108109
    spawnAreaType point
    spawnerType 13987
    points
        point
            pos ( x 491.969, y 382.269, z 150.616 )
            zRot 3.14159
spawner
    spawnerId 108845
    spawnAreaType area
    spawnerType 13884
    points
        point
            pos ( x 690.737, y 401.21, z 154.156 )
            zRot -0.785393
        point
            pos ( x 700.0, y 420.5, z 155.0 )
"""

WORLD = """<World name="w" resolution="1024" cellXCount="35" cellYCount="38">
 <ZoneList>
  <Zone name="zone_a" id="278" originX="0" originY="0">
  <Zone name="zone_b" id="307" originX="22" originY="26">
 </ZoneList>
</World>
"""


class ParseSpawners(unittest.TestCase):
    def test_blocks_points_and_fields(self):
        rows = parse_spawners(G)
        self.assertEqual([r["id"] for r in rows], [108109, 108845])
        self.assertEqual([r["template"] for r in rows], [13987, 13884])
        self.assertEqual(rows[0]["area"], "point")
        self.assertEqual(rows[1]["area"], "area")
        self.assertEqual(len(rows[1]["points"]), 2)
        self.assertEqual(rows[0]["points"][0], [491.969, 382.269, 150.616])
        self.assertEqual(rows[0]["zrot"], [3.14159])

    def test_nested_point_keyword_is_not_a_spawner(self):
        rows = parse_spawners("spawner\n    spawnerId 1\n    points\n        point\n")
        self.assertEqual(len(rows), 1)
        self.assertEqual(rows[0]["points"], [])


class CoordinateTransform(unittest.TestCase):
    def test_origin_times_1024_plus_local(self):
        self.assertEqual(transform((0, 0), 491.969, 382.269), (491.969, 382.269))
        self.assertEqual(transform((22, 26), 1.5, 2.5), (22529.5, 26626.5))
        self.assertEqual(transform((3, 3), 0.0, 0.0), (3072.0, 3072.0))

    def test_world_xml_origins(self):
        with tempfile.TemporaryDirectory() as tmp:
            os.makedirs(os.path.join(tmp, "game", "worlds", "main_world"))
            with open(
                os.path.join(tmp, "game", "worlds", "main_world", "world.xml"),
                "w",
                encoding="utf-8",
            ) as f:
                f.write(WORLD)
            origins = zone_origins(tmp)
        self.assertEqual(origins[("main_world", 278)][:2], (0, 0))
        self.assertEqual(origins[("main_world", 307)][:2], (22, 26))
        self.assertEqual(origins[("main_world", 307)][2], "zone_b")


class ExistingEventCrossCheck(unittest.TestCase):
    """154 of the 199 shipped event entries sit within 5 m of their 10.x editor placement."""

    def test_shipped_events_match_editor_coordinates(self):
        root = os.environ.get("AAEMU_SPAWN_AUDIT")
        if not root:
            self.skipTest("AAEMU_SPAWN_AUDIT not set")
        import sys

        sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
        from spawn_pak import read_spawner_file, spawner_files

        origins10 = zone_origins(os.path.join(root, "w10"))
        editor = {}
        for world, zone, path in spawner_files(os.path.join(root, "pak10")):
            origin = origins10.get((world, zone))
            if not origin:
                continue
            for s in read_spawner_file(path):
                if s["points"]:
                    editor.setdefault((world, s["id"]), (origin, s["points"][0]))
        worlds = os.path.join(
            os.path.dirname(os.path.abspath(__file__)), "..", "..", "crates", "aaemu-game",
            "app", "Data", "Worlds",
        )
        total = matched = 0
        for path in glob.glob(worlds + "/*/npc_spawns.json"):
            world = path.replace("\\", "/").split("/")[-2]
            for e in world_entries(path):
                if not e.get("NpcSpawnerIds"):
                    continue
                if str(e.get("Title", "")).startswith("spawn-fill: 10.x"):
                    continue  # generated by this tool; the cross-check is for the shipped 199
                p = e.get("Position") or {}
                for sid in e["NpcSpawnerIds"]:
                    total += 1
                    found = editor.get((world, sid))
                    if found is None:
                        continue
                    (ox, oy, _), local = found
                    x, y = transform((ox, oy), local[0], local[1])
                    if math.hypot(x - p.get("X", 0), y - p.get("Y", 0)) <= 5.0:
                        matched += 1
        self.assertGreaterEqual(matched, 150, f"{matched}/{total} within 5 m")
        self.assertLessEqual(abs(matched - 154), 4, f"{matched}/{total} within 5 m")


if __name__ == "__main__":
    unittest.main()
